//! Deterministic typing feedback, independent of windows and input hooks.
//!
//! Adapters filter shortcuts and modifiers before calling [`TypingState::apply`].
//! The state retains physical key identifiers only while keys are held.

#![deny(missing_docs)]
#![forbid(unsafe_code)]

pub mod animation;

use std::collections::{BTreeMap, btree_map::Entry};

/// Opaque physical key identifier within one input source.
///
/// This identifies a key, not the character produced by a keyboard layout or IME.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct KeyId(u32);

impl KeyId {
    /// Wraps an adapter's physical key code. Reset before changing input sources.
    pub const fn new(code: u32) -> Self {
        Self(code)
    }
}

/// The hand assigned to a fresh key press.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Hand {
    /// Left hand, also the first hand after a reset.
    #[default]
    Left,
    /// Right hand.
    Right,
}

impl Hand {
    fn opposite(self) -> Self {
        match self {
            Self::Left => Self::Right,
            Self::Right => Self::Left,
        }
    }
}

/// A filtered input event with no typed text.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InputEvent {
    /// A physical key went down. OS auto-repeat must set `repeat` to true.
    Press {
        /// The physical key identifier.
        key: KeyId,
        /// Whether the event was generated by holding an already pressed key.
        repeat: bool,
    },
    /// A physical key went up, even if shortcuts are currently being filtered.
    Release(KeyId),
    /// Release all keys on source disconnect, permission loss, pause, or sleep.
    Reset,
}

/// Target hand positions for a renderer. Animation interpolation is separate.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Pose {
    /// At least one held key is assigned to the left hand.
    pub left_pressed: bool,
    /// At least one held key is assigned to the right hand.
    pub right_pressed: bool,
}

/// State and optional one-shot feedback produced by an input event.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Feedback {
    /// The new target pose, including all keys that are still held.
    pub pose: Pose,
    /// Emit a sound or press impulse once, only for a fresh key press.
    pub strike: Option<Hand>,
}

/// Alternates fresh key presses and holds each assigned hand until release.
///
/// Duplicate presses are ignored. Repeated events cannot revive keys after a
/// reset, and releasing one key does not lift a hand assigned to another key.
#[derive(Default)]
pub struct TypingState {
    held: BTreeMap<KeyId, Hand>,
    next_hand: Hand,
}

impl TypingState {
    /// Applies an event from the active input source.
    pub fn apply(&mut self, event: InputEvent) -> Feedback {
        let strike = match event {
            InputEvent::Press { key, repeat: false } => match self.held.entry(key) {
                Entry::Vacant(entry) => {
                    let hand = self.next_hand;
                    entry.insert(hand);
                    self.next_hand = hand.opposite();
                    Some(hand)
                }
                Entry::Occupied(_) => None,
            },
            InputEvent::Press { repeat: true, .. } => None,
            InputEvent::Release(key) => {
                self.held.remove(&key);
                None
            }
            InputEvent::Reset => {
                self.held.clear();
                self.next_hand = Hand::Left;
                None
            }
        };

        Feedback {
            pose: self.pose(),
            strike,
        }
    }

    /// Returns the target pose without advancing or changing the state.
    pub fn pose(&self) -> Pose {
        Pose {
            left_pressed: self.held.values().any(|hand| *hand == Hand::Left),
            right_pressed: self.held.values().any(|hand| *hand == Hand::Right),
        }
    }
}
